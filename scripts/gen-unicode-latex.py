#!/usr/bin/env python3
"""Regenerate the pinned Unicode/name to LaTeX table; see vendored-assets §3.7."""

import argparse
import hashlib
import io
import os
from pathlib import Path
import re
import sys
import tarfile
import tempfile
import tomllib
import unicodedata
import urllib.request


ROOT = Path(__file__).resolve().parent.parent
PINS = {
    "tylax": ("0.3.8", "145d65de1d49c044ae64c664edf034f4956c17dbddaa0cf2fad3afea85400672"),
    "codex": ("0.3.0", "0732ab1a27b4ea05e6f9f60a5122c9924dd5123defde0d8e907f58cf643d40e6"),
    "typst-syntax": ("0.15.1", "92a20d79df5d10c7fb0b4f7c18e4b2671edfc21e5ed9ad9894e18cccefd1c70f"),
}
MEMBERS = {
    "tylax": ["src/data/maps.rs", "src/core/typst2latex/utils.rs"],
    "codex": ["src/modules/sym.txt"],
    "typst-syntax": ["src/ast.rs"],
}
HEADER = """# Generated by scripts/gen-unicode-latex.py; do not edit. Change scripts/unicode-latex-overrides.toml.
# Derived from tylax 0.3.8 (Apache-2.0, https://github.com/scipenai/tylax): TYPST_TO_TEX in
# src/data/maps.rs and UNICODE_TO_LATEX in src/core/typst2latex/utils.rs, modified by writer
# (normalised, resolved through codex 0.3.0, merged, overridden). License: vendor/crates/tylax/LICENSE.
"""


def rust_string(text):
    def escape(match):
        value = match[1]
        if value.startswith("u{"):
            return chr(int(value[2:-1], 16))
        escapes = {
            "\\": "\\", '"': '"', "'": "'", "n": "\n",
            "r": "\r", "t": "\t", "0": "\0"
        }
        if value not in escapes:
            raise ValueError(f"unsupported Rust escape: \\{value}")
        return escapes[value]

    return re.sub(r"\\(u\{[0-9a-fA-F]+\}|.)", escape, text)


def block(text, start, end):
    lines = iter(text.splitlines())
    for line in lines:
        if start in line:
            break
    else:
        raise ValueError(f"missing source block: {start}")
    result = []
    for line in lines:
        if re.fullmatch(end, line):
            return result
        result.append(line)
    raise ValueError(f"unterminated source block: {start}")


def parse_names(text):
    pattern = re.compile(r'\s*"((?:[^"\\]|\\.)*)"\s*=>\s*"((?:[^"\\]|\\.)*)",\s*')
    rows = []
    for line in block(text, "pub static TYPST_TO_TEX", r"};"):
        if match := pattern.fullmatch(line):
            rows.append(tuple(rust_string(value) for value in match.groups()))
    require_count("name entries", len(rows), 532)
    return rows


def parse_chars(text):
    pattern = re.compile(r'''\s*m\.insert\('((?:[^'\\]|\\.)*)',\s*"((?:[^"\\]|\\.)*)"\);\s*''')
    rows = []
    for line in block(text, "pub static ref UNICODE_TO_LATEX", r"\s*};"):
        if match := pattern.fullmatch(line):
            char, tex = (rust_string(value) for value in match.groups())
            if len(char) != 1:
                raise ValueError("Unicode table key is not one scalar")
            rows.append((char, tex))
    require_count("character entries", len(rows), 159)
    return rows


def parse_shorthands(text):
    pattern = re.compile(r'''\s*\("((?:[^"\\]|\\.)*)",\s*'((?:[^'\\]|\\.)*)'\),\s*''')
    rows = []
    for line in block(text, "struct MathShorthand", r"\s*];"):
        if match := pattern.fullmatch(line):
            rows.append(tuple(rust_string(value) for value in match.groups()))
    require_count("math shorthands", len(rows), 38)
    return dict(rows)


def codex_value(text):
    def escape(match):
        if match[1] is not None:
            return chr(int(match[1], 16))
        value = match[2]
        number = {"text": 15, "emoji": 16}.get(value)
        if number is None:
            number = int(value)
        if not 1 <= number <= 16:
            raise ValueError("invalid codex variation selector")
        return chr(0xFE00 + number - 1)

    return re.sub(r"\\u\{([0-9A-Fa-f]+)\}|\\vs\{([^}]+)\}", escape, text)


def parse_codex(text):
    modules = []
    symbols = {}
    current = None
    plain = variants = 0
    for raw in text.splitlines():
        line = raw.split("//", 1)[0].strip()
        if not line or line.startswith("@deprecated:"):
            continue
        if line.endswith(" {"):
            modules.append(line[:-2])
            current = None
        elif line == "}":
            if not modules:
                raise ValueError("unbalanced codex module")
            modules.pop()
            current = None
        elif line.startswith("."):
            if current is None:
                raise ValueError("codex variant without symbol")
            modifiers, value = line.split(None, 1)
            symbols[current].append((
                frozenset(modifiers[1:].split(".")), codex_value(value)
            ))
            variants += 1
        else:
            words = line.split(None, 1)
            current = ".".join([*modules, words[0]])
            if current in symbols:
                raise ValueError(f"duplicate codex symbol: {current}")
            symbols[current] = []
            if len(words) == 2:
                symbols[current].append((frozenset(), codex_value(words[1])))
                plain += 1
    if modules:
        raise ValueError("unclosed codex module")
    require_count("codex symbols", len(symbols), 334)
    require_count("codex plain values", plain, 288)
    require_count("codex variants", variants, 918)
    variants_only = sum(
        not any(not mods for mods, _ in items) for items in symbols.values()
    )
    require_count("codex variants-only symbols", variants_only, 46)
    return symbols


def require_count(label, actual, expected):
    if actual != expected:
        raise ValueError(f"{label}: expected {expected}, found {actual}")


def read_sources(archive_dir, temporary):
    sources = {}
    for name, (version, digest) in PINS.items():
        filename = f"{name}-{version}.crate"
        if archive_dir is None:
            url = f"https://static.crates.io/crates/{name}/{filename}"
            path = Path(temporary) / filename
            with urllib.request.urlopen(url, timeout=60) as response:
                data = response.read(2 * 1024 * 1024)
            path.write_bytes(data)
        else:
            path = archive_dir / filename
            data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f"SHA-256 mismatch for {filename}")
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
            for member in MEMBERS[name]:
                full = f"{name}-{version}/{member}"
                info = archive.getmember(full)
                if not info.isfile() or info.size > 4 * 1024 * 1024:
                    raise ValueError(f"invalid archive member: {full}")
                stream = archive.extractfile(info)
                if stream is None:
                    raise ValueError(f"unreadable archive member: {full}")
                with stream:
                    sources[(name, member)] = stream.read().decode("utf-8")
    return sources


def resolve(name, symbols, shorthands):
    if name in shorthands:
        return shorthands[name]
    parts = name.split(".")
    if any(not part for part in parts):
        return None
    for index in range(len(parts), 0, -1):
        if items := symbols.get(".".join(parts[:index])):
            requested = frozenset(parts[index:])
            matches = [(mods, value) for mods, value in items if requested <= mods]
            if not matches:
                return None
            _, value = min(matches, key=lambda item: len(item[0]))
            value = value.rstrip("\ufe0e\ufe0f")
            return value if len(value) == 1 else None
    return None


def normalise(value):
    return "\\" + value if re.match(r"^[A-Za-z]{2}", value) else value


def override_tables(data):
    if set(data) - {"names", "chars", "packages"}:
        raise ValueError("unknown overrides table")
    result = {}
    for key in ["names", "chars", "packages"]:
        items = data.get(key, {})
        if not isinstance(items, dict) or any(
            not isinstance(value, str) for value in items.values()
        ):
            raise ValueError(f"{key} overrides must be a table of strings")
        result[key] = items
    for command, package in result["packages"].items():
        if (
            not re.fullmatch(r"\\[A-Za-z]+", command)
            or not re.fullmatch(r"[A-Za-z][A-Za-z0-9-]*", package)
        ):
            raise ValueError(f"invalid package override: {command}")
    return result


def char_key(key):
    if not re.fullmatch(r"U\+[0-9A-Fa-f]{4,6}", key):
        raise ValueError(f"invalid character override key: {key}")
    value = int(key[2:], 16)
    if value > 0x10FFFF or 0xD800 <= value <= 0xDFFF:
        raise ValueError(f"invalid Unicode scalar: {key}")
    return chr(value)


def alnum(char, chars):
    name = unicodedata.name(char, "")
    if not name.startswith("MATHEMATICAL "):
        return None
    base = unicodedata.normalize("NFKC", char)
    ascii_base = len(base) == 1 and base.isascii() and base.isalnum()
    if not ascii_base and base not in chars:
        return None
    tex = base if ascii_base else chars[base]["tex"]
    styles = {
        "BOLD", "ITALIC", "SCRIPT", "FRAKTUR", "DOUBLE-STRUCK",
        "SANS-SERIF", "MONOSPACE",
    }
    style = " ".join(word for word in name.split()[1:] if word in styles)
    if (
        style in {"SCRIPT", "BOLD SCRIPT", "DOUBLE-STRUCK"}
        and not (ascii_base and "A" <= base <= "Z")
    ):
        return None
    formats = {
        "BOLD": r"\mathbf{%s}" if ascii_base else r"\boldsymbol{%s}",
        "ITALIC": r"\mathit{%s}", "BOLD ITALIC": r"\boldsymbol{%s}",
        "SCRIPT": r"\mathcal{%s}", "BOLD SCRIPT": r"\boldsymbol{\mathcal{%s}}",
        "FRAKTUR": r"\mathfrak{%s}", "BOLD FRAKTUR": r"\boldsymbol{\mathfrak{%s}}",
        "DOUBLE-STRUCK": r"\mathbb{%s}", "SANS-SERIF": r"\mathsf{%s}",
        "SANS-SERIF ITALIC": r"\mathsf{%s}",
        "SANS-SERIF BOLD": r"\boldsymbol{\mathsf{%s}}",
        "SANS-SERIF BOLD ITALIC": r"\boldsymbol{\mathsf{%s}}",
        "MONOSPACE": r"\mathtt{%s}",
    }
    return formats[style] % tex if style in formats else None


def generate(sources, overrides):
    rows = parse_names(sources[("tylax", "src/data/maps.rs")])
    unicode_rows = parse_chars(sources[("tylax", "src/core/typst2latex/utils.rs")])
    shorthands = parse_shorthands(sources[("typst-syntax", "src/ast.rs")])
    symbols = parse_codex(sources[("codex", "src/modules/sym.txt")])
    names = {name: {"tex": normalise(tex)} for name, tex in rows}
    for name, tex in sorted(overrides["names"].items()):
        if tex:
            names[name] = {"tex": tex}
        else:
            names.pop(name, None)
    chars = {}
    conflicts = []
    unresolved = []

    def put(char, tex, origin, overwrite):
        if char in chars and chars[char]["tex"] != tex:
            conflicts.append(
                f"U+{ord(char):04X}: {chars[char]['tex']!r} "
                f"versus {tex!r} ({origin})"
            )
        if overwrite or char not in chars:
            chars[char] = {"char": char, "tex": tex, "from": origin}

    for name, entry in names.items():
        char = resolve(name, symbols, shorthands)
        if char is None:
            unresolved.append(name)
        else:
            put(char, entry["tex"], f"names:{name}", False)
    for char, tex in unicode_rows:
        put(char, tex, "chars", True)
    deleted = set()
    for key, tex in sorted(overrides["chars"].items()):
        char = char_key(key)
        if tex:
            put(char, tex, "override", True)
        else:
            deleted.add(char)
            chars.pop(char, None)
    before_alnum = len(chars)
    for value in range(0x1D400, 0x1D800):
        char = chr(value)
        if char not in chars and char not in deleted and (tex := alnum(char, chars)):
            put(char, tex, "alnum", False)
    for entry in [*names.values(), *chars.values()]:
        packages = {
            overrides["packages"][command]
            for command in re.findall(r"\\[A-Za-z]+", entry["tex"])
            if command in overrides["packages"]
        }
        if len(packages) > 1:
            raise ValueError(f"two packages in one value: {entry['tex']}")
        if packages:
            entry["package"] = packages.pop()
    report = {
        "names": len(names), "chars": len(chars), "base_chars": before_alnum,
        "alnum": len(chars) - before_alnum, "conflicts": conflicts,
        "unresolved": unresolved,
    }
    if not any(overrides.values()):
        for label, expected in [
            ("names", 532), ("chars", 1292),
            ("base_chars", 405), ("alnum", 887)
        ]:
            require_count(f"empty override {label}", report[label], expected)
        require_count("empty override conflicts", len(conflicts), 17)
        require_count("empty override unresolved", len(unresolved), 87)
    return names, chars, report


def quote(text):
    result = ['"']
    for char in text:
        if char in {'"', "\\"}:
            result.append("\\" + char)
        elif ord(char) < 32 or ord(char) == 127:
            result.append(f"\\u{ord(char):04X}")
        else:
            result.append(char)
    return "".join([*result, '"'])


def serialize(names, chars):
    lines = [HEADER.rstrip(), "", "[source]"]
    lines.extend(f"{name} = {quote(version)}" for name, (version, _) in PINS.items())
    sections = [
        ("names", sorted(names.items())),
        ("chars", [
            (f"U+{ord(char):04X}", row) for char, row in sorted(chars.items())
        ]),
    ]
    for title, entries in sections:
        lines.extend(["", f"[{title}]"])
        for key, row in entries:
            fields = ", ".join(
                f"{field} = {quote(row[field])}"
                for field in ["char", "tex", "package", "from"]
                if field in row
            )
            lines.append(f"{quote(key)} = {{ {fields} }}")
    return "\n".join(lines) + "\n"


def write_output(output, text, check):
    encoded = text.encode("utf-8")
    if check:
        if not output.is_file() or output.read_bytes() != encoded:
            raise ValueError(f"generated table differs: {output}")
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(
            dir=output.parent, prefix=".unicode-latex-", delete=False
        ) as stream:
            temporary = Path(stream.name)
            stream.write(encoded)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, output)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--archive-dir", type=Path)
    parser.add_argument(
        "--overrides", type=Path,
        default=ROOT / "scripts/unicode-latex-overrides.toml"
    )
    parser.add_argument(
        "--output", type=Path, default=ROOT / "assets/math/unicode-latex.toml"
    )
    args = parser.parse_args(argv)
    try:
        overrides = override_tables(tomllib.loads(
            args.overrides.read_text(encoding="utf-8")
        ))
        with tempfile.TemporaryDirectory(prefix="writer-unicode-latex-") as temporary:
            sources = read_sources(args.archive_dir, temporary)
        names, chars, report = generate(sources, overrides)
        print(
            f"names {report['names']}, chars {report['chars']} "
            f"({report['base_chars']} names/chars, {report['alnum']} alnum), "
            f"conflicts {len(report['conflicts'])}, "
            f"unresolved {len(report['unresolved'])}",
            file=sys.stderr,
        )
        for value in report["conflicts"]:
            print(f"conflict {value}", file=sys.stderr)
        for value in report["unresolved"]:
            print(f"unresolved {value}", file=sys.stderr)
        write_output(args.output, serialize(names, chars), args.check)
    except (ValueError, OSError, KeyError, tarfile.TarError) as error:
        print(f"gen-unicode-latex: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
