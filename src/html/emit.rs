/// Escapes exactly the five HTML-sensitive characters, preserving other text.
pub fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for character in text.chars() {
        match character {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            other => out.push(other),
        }
    }
    out
}

/// Emits deterministic HTML fragments, leaving asset placeholders unresolved.
pub fn emit(document: &Document, opts: &mut EmitOptions<'_>) -> Emitted {
    let lang = LangTag::effective(&document.meta, opts.config)
        .unwrap_or_else(|| LangTag { lang: "en".into(), region: None });
    let mut emitter = Emitter {
        document,
        opts,
        lang,
        notes: NotePlan::new(document),
        anchor_depth: 0,
        deferred_notes: String::new(),
        inline_ids: true,
        abstract_mode: false,
        current_span: None,
    };
    let title_block = emitter.title_block();
    let body = emitter.blocks(&document.blocks);
    let footnotes = emitter.footnotes();
    let depth = match emitter.opts.config.document.toc {
        Toc::Depth(depth) => depth,
        _ => 3,
    };
    let toc = emitter.toc(depth, None);
    let main = format!(
        "<main data-writer-document>\n{title_block}{body}{footnotes}</main>\n"
    );
    Emitted {
        title_block,
        body,
        footnotes,
        toc,
        main,
        math: emitter.opts.math.usage(),
    }
}

struct Emitter<'d, 'o, 'r> {
    document: &'d Document,
    opts: &'o mut EmitOptions<'r>,
    lang: LangTag,
    notes: NotePlan<'d>,
    anchor_depth: usize,
    deferred_notes: String,
    inline_ids: bool,
    abstract_mode: bool,
    current_span: Option<&'d SourceSpan>,
}

/// A note's content and the context in which its first reference occurs.
#[derive(Clone, Copy)]
struct NoteBody<'d> {
    blocks: &'d [Block],
    abstract_mode: bool,
    span: Option<&'d SourceSpan>,
}

#[derive(Default)]
struct NotePlan<'d> {
    bodies: BTreeMap<u32, NoteBody<'d>>,
    ordinals: BTreeMap<*const Inline, u32>,
    counts: BTreeMap<u32, u32>,
}

impl<'d> NotePlan<'d> {
    fn new(document: &'d Document) -> Self {
        let mut plan = Self::default();
        if let Some(abstract_) = &document.meta.abstract_ {
            plan.blocks(abstract_, document, true, None);
        }
        plan.blocks(&document.blocks, document, false, None);
        plan
    }

    fn blocks(
        &mut self, blocks: &'d [Block], document: &'d Document,
        abstract_mode: bool, enclosing: Option<&'d SourceSpan>,
    ) {
        for block in blocks {
            let span = if abstract_mode {
                None
            } else {
                block.span().or(enclosing)
            };
            match block {
                Block::Heading { inlines, .. }
                | Block::Paragraph { inlines, .. } => {
                    self.inlines(inlines, document, abstract_mode, span)
                }
                Block::BlockQuote { blocks, .. }
                | Block::Div { blocks, .. } => {
                    self.blocks(blocks, document, abstract_mode, span)
                }
                Block::List { items, .. } => {
                    for item in items {
                        self.blocks(
                            &item.blocks, document, abstract_mode, span,
                        );
                    }
                }
                Block::DefinitionList { items, .. } => {
                    for item in items {
                        self.inlines(&item.term, document, abstract_mode, span);
                        for blocks in &item.definitions {
                            self.blocks(blocks, document, abstract_mode, span);
                        }
                    }
                }
                Block::Callout { title, blocks, .. } => {
                    if let Some(title) = title {
                        self.inlines(title, document, abstract_mode, span);
                    }
                    self.blocks(blocks, document, abstract_mode, span);
                }
                Block::Figure { kind, caption, body, .. } => {
                    self.figure(
                        *kind,
                        caption.as_deref(),
                        body,
                        document,
                        abstract_mode,
                        span,
                    );
                }
                Block::Table { head, body, foot, .. } => {
                    for row in head.iter().chain(body).chain(foot) {
                        for cell in &row.cells {
                            self.inlines(
                                &cell.inlines, document, abstract_mode, span,
                            );
                        }
                    }
                }
                Block::Cell(cell) if cell.show_output => {
                    for output in &cell.outputs {
                        self.blocks(
                            output.pick("html"),
                            document,
                            abstract_mode,
                            span,
                        );
                    }
                }
                Block::Bibliography { .. } => {
                    self.bibliography(document, abstract_mode, span)
                }
                _ => {}
            }
        }
    }

    fn figure(
        &mut self, kind: FigureKind, caption: Option<&'d [Inline]>,
        body: &'d [Block], document: &'d Document, abstract_mode: bool,
        span: Option<&'d SourceSpan>,
    ) {
        let first = matches!(kind, FigureKind::Table | FigureKind::Listing);
        if first && let Some(caption) = caption {
            self.inlines(caption, document, abstract_mode, span);
        }
        self.blocks(body, document, abstract_mode, span);
        if !first && let Some(caption) = caption {
            self.inlines(caption, document, abstract_mode, span);
        }
    }

    fn bibliography(
        &mut self, document: &'d Document, abstract_mode: bool,
        span: Option<&'d SourceSpan>,
    ) {
        if let Some(bibliography) = &document.resolved.bibliography {
            for entry in &bibliography.entries {
                if let Some(prefix) = &entry.prefix {
                    self.inlines(prefix, document, abstract_mode, span);
                }
                self.inlines(&entry.inlines, document, abstract_mode, span);
            }
        }
    }

    fn inlines(
        &mut self, inlines: &'d [Inline], document: &'d Document,
        abstract_mode: bool, span: Option<&'d SourceSpan>,
    ) {
        for inline in inlines {
            match inline {
                Inline::Footnote { blocks, number: Some(number), .. } => {
                    self.reference(inline, *number);
                    if !self.bodies.contains_key(number) {
                        self.bodies.insert(
                            *number,
                            NoteBody { blocks, abstract_mode, span },
                        );
                        self.blocks(blocks, document, abstract_mode, span);
                    }
                }
                Inline::FootnoteRef { number: Some(number), .. } => {
                    self.reference(inline, *number)
                }
                Inline::Emph { inlines }
                | Inline::Strong { inlines }
                | Inline::Strikeout { inlines }
                | Inline::Subscript { inlines }
                | Inline::Superscript { inlines }
                | Inline::Underline { inlines }
                | Inline::SmallCaps { inlines }
                | Inline::Span { inlines, .. }
                | Inline::Link { inlines, .. } => {
                    self.inlines(inlines, document, abstract_mode, span)
                }
                Inline::Ref { resolved: Some(reference), .. } => {
                    self.inlines(&reference.text, document, abstract_mode, span)
                }
                Inline::Cite { resolved: Some(citation), .. } => self
                    .inlines(&citation.inlines, document, abstract_mode, span),
                _ => {}
            }
        }
    }

    fn reference(&mut self, inline: &Inline, number: u32) {
        let count = self.counts.entry(number).or_default();
        *count += 1;
        self.ordinals.insert(inline, *count);
    }
}

impl<'d> Emitter<'d, '_, '_> {
    fn positions(
        &self, span: Option<&SourceSpan>,
    ) -> Vec<(&'static str, Option<String>)> {
        let Some(span) =
            span.filter(|_| self.opts.positions && !self.abstract_mode)
        else {
            return Vec::new();
        };
        let source = span
            .file
            .as_ref()
            .and_then(|path| {
                self.opts.includes.iter().position(|included| included == path)
            })
            .map_or(0, |index| index + 1);
        let mut positions = vec![
            value(
                "data-sourcepos",
                format!("{}-{}", span.start_line, span.end_line),
            ),
            value("data-source", source.to_string()),
        ];
        if let Some(cell) = span.cell {
            positions.push(value("data-cell", cell.to_string()));
        }
        positions
    }

    fn tag(
        &self, name: &str, attrs: &Attrs, classes: &[&str],
        own: &[(&str, Option<String>)], consumed: &[&str],
        span: Option<&SourceSpan>, inline: bool,
    ) -> String {
        let positions = if inline {
            Vec::new()
        } else {
            self.positions(span)
        };
        start_tag(
            name,
            attrs,
            classes,
            own,
            consumed,
            &positions,
            !inline || self.inline_ids,
        )
    }

    fn inlines(&mut self, inlines: &'d [Inline]) -> String {
        let mut out = String::new();
        for inline in inlines {
            out.push_str(&self.inline(inline));
        }
        out
    }

    fn inline(&mut self, inline: &'d Inline) -> String {
        match inline {
            Inline::Text { text } => escape(text),
            Inline::Emph { inlines } => self.wrap("em", inlines),
            Inline::Strong { inlines } => self.wrap("strong", inlines),
            Inline::Strikeout { inlines } => self.wrap("del", inlines),
            Inline::Subscript { inlines } => self.wrap("sub", inlines),
            Inline::Superscript { inlines } => self.wrap("sup", inlines),
            Inline::Underline { inlines } => self.wrap("u", inlines),
            Inline::SmallCaps { inlines } => {
                format!(
                    "<span class=\"smallcaps\">{}</span>",
                    self.inlines(inlines)
                )
            }
            Inline::Code { text, attrs } => format!(
                "{}{}</code>",
                self.tag("code", attrs, &[], &[], &[], None, true),
                escape(text)
            ),
            Inline::Math { source, dialect } => {
                self.math(source, *dialect, false, self.current_span)
            }
            Inline::Link { inlines, url, title, attrs } => {
                self.link(inlines, url, title.as_deref(), attrs)
            }
            Inline::Image { alt, url, title, attrs } => {
                self.image(alt, url, title.as_deref(), attrs)
            }
            Inline::Footnote { number, .. }
            | Inline::FootnoteRef { number, .. } => {
                self.note_reference(inline, *number)
            }
            Inline::Ref { target, resolved, .. } => {
                self.reference(target, resolved.as_ref())
            }
            Inline::Cite { items, resolved, .. } => {
                self.citation(items, resolved.as_ref())
            }
            Inline::LineBreak => "<br>\n".into(),
            Inline::SoftBreak => " ".into(),
            Inline::Span { attrs, inlines } => format!(
                "{}{}</span>",
                self.tag("span", attrs, &[], &[], &[], None, true),
                self.inlines(inlines)
            ),
            Inline::Raw { format, text } if format == "html" => text.clone(),
            Inline::Raw { .. } => String::new(),
        }
    }

    fn link(
        &mut self, inlines: &'d [Inline], url: &str, title: Option<&str>,
        attrs: &Attrs,
    ) -> String {
        if self.anchor_depth > 0 {
            return self.inlines(inlines);
        }
        let mut own = vec![value("href", url)];
        if let Some(title) = title {
            own.push(value("title", title));
        }
        let open = self.tag("a", attrs, &[], &own, &[], None, true);
        self.anchor(open, inlines)
    }

    fn note_reference(
        &mut self, inline: &Inline, number: Option<u32>,
    ) -> String {
        let Some(number) = number else {
            return String::new();
        };
        let ordinal = self
            .notes
            .ordinals
            .get(&(inline as *const Inline))
            .copied()
            .unwrap_or(1);
        let note = footnote_reference(number, ordinal);
        if self.anchor_depth > 0 {
            self.deferred_notes.push_str(&note);
            String::new()
        } else {
            note
        }
    }

    fn reference(
        &mut self, target: &str, resolved: Option<&'d ResolvedRef>,
    ) -> String {
        let Some(reference) = resolved else {
            let text = escape(&format!("[?{target}]"));
            return if self.anchor_depth > 0 {
                text
            } else {
                format!("<span class=\"ref unresolved\">{text}</span>")
            };
        };
        if self.anchor_depth > 0 {
            return self.inlines(&reference.text);
        }
        if reference.anchor.is_empty() {
            return format!(
                "<span class=\"ref\">{}</span>",
                self.inlines(&reference.text)
            );
        }
        self.anchor(
            format!(
                "<a class=\"ref\" href=\"#{}\">",
                escape(&reference.anchor)
            ),
            &reference.text,
        )
    }

    fn citation(
        &mut self, items: &[CiteItem], resolved: Option<&'d ResolvedCite>,
    ) -> String {
        let keys: Vec<_> = items.iter().map(|item| item.key.as_str()).collect();
        let (class, content) = match resolved {
            Some(citation) => ("citation", self.inlines(&citation.inlines)),
            None => (
                "citation unresolved",
                escape(&format!("[?{}]", keys.join("; "))),
            ),
        };
        format!(
            "<span class=\"{class}\" data-cites=\"{}\">{content}</span>",
            escape(&keys.join(" "))
        )
    }

    fn wrap(&mut self, tag: &str, inlines: &'d [Inline]) -> String {
        format!("<{tag}>{}</{tag}>", self.inlines(inlines))
    }

    fn anchor(&mut self, open: String, inlines: &'d [Inline]) -> String {
        self.anchor_depth += 1;
        let content = self.inlines(inlines);
        self.anchor_depth -= 1;
        let mut out = format!("{open}{content}</a>");
        if self.anchor_depth == 0 {
            out.push_str(&std::mem::take(&mut self.deferred_notes));
        }
        out
    }

    fn math(
        &mut self, source: &str, dialect: MathDialect, display: bool,
        span: Option<&SourceSpan>,
    ) -> String {
        self.opts.math.equation(
            &MathRequest { source, dialect, display, span },
            self.opts.assets,
            self.opts.diagnostics,
        )
    }

    fn image(
        &self, alt: &[Inline], url: &str, title: Option<&str>, attrs: &Attrs,
    ) -> String {
        let mut own =
            vec![value("src", url), value("alt", ir::plain_text(alt))];
        if let Some(title) = title {
            own.push(value("title", title));
        }
        let styles: Vec<_> = ["width", "height"]
            .into_iter()
            .filter_map(|key| {
                let size = attrs.pairs.get(key)?;
                let unit = if size
                    .bytes()
                    .all(|byte| byte.is_ascii_digit() || byte == b'.')
                {
                    "px"
                } else {
                    ""
                };
                Some(format!("{key}:{size}{unit}"))
            })
            .collect();
        if !styles.is_empty() {
            own.push(value("style", styles.join(";")));
        }
        self.tag("img", attrs, &[], &own, &["width", "height"], None, true)
    }

    fn blocks(&mut self, blocks: &'d [Block]) -> String {
        let mut out = String::new();
        for block in blocks {
            out.push_str(&self.block(block));
        }
        out
    }

    fn block(&mut self, block: &'d Block) -> String {
        let previous = self.current_span;
        if !self.abstract_mode {
            self.current_span = block.span().or(previous);
        }
        let out = self.block_content(block);
        self.current_span = previous;
        out
    }

    fn block_content(&mut self, block: &'d Block) -> String {
        let span = block.span();
        let empty = Attrs::default();
        match block {
            Block::Heading { level, inlines, attrs, number, .. } => {
                let tag = format!("h{level}");
                format!(
                    "{}{}{}</{tag}>\n",
                    self.tag(&tag, attrs, &[], &[], &[], span, false),
                    number_html(number.as_deref()),
                    self.inlines(inlines)
                )
            }
            Block::Paragraph { inlines, .. } => format!(
                "{}{}</p>\n",
                self.tag("p", &empty, &[], &[], &[], span, false),
                self.inlines(inlines)
            ),
            Block::BlockQuote { blocks, .. } => format!(
                "{}\n{}</blockquote>\n",
                self.tag("blockquote", &empty, &[], &[], &[], span, false),
                self.blocks(blocks)
            ),
            Block::List { kind, tight, items, .. } => {
                self.list(kind, *tight, items, span)
            }
            Block::DefinitionList { items, .. } => {
                self.definitions(items, span)
            }
            Block::CodeBlock { lang, text, attrs, .. } => {
                self.code_block(lang.as_deref(), text, attrs, span)
            }
            Block::Figure { kind, caption, body, attrs, number, .. } => self
                .figure(
                    *kind,
                    caption.as_deref(),
                    body,
                    attrs,
                    number.as_deref(),
                    span,
                ),
            Block::Table { columns, head, body, foot, attrs, .. } => {
                self.table(columns, head, body, foot, attrs, span)
            }
            Block::Math { source, dialect, attrs, number, .. } => self
                .display_math(source, *dialect, attrs, number.as_deref(), span),
            Block::Callout { kind, title, blocks, attrs, .. } => {
                self.callout(kind, title.as_deref(), blocks, attrs, span)
            }
            Block::Div { attrs, blocks, .. } => self.div(attrs, blocks, span),
            Block::Raw { format, text, .. } if format == "html" => {
                let mut text = text.clone();
                if !text.ends_with('\n') {
                    text.push('\n');
                }
                text
            }
            Block::Raw { .. } => String::new(),
            Block::ThematicBreak { .. } => format!(
                "{}\n",
                self.tag("hr", &empty, &[], &[], &[], span, false)
            ),
            Block::PageBreak { .. } => format!(
                "{}</div>\n",
                self.tag("div", &empty, &["page-break"], &[], &[], span, false)
            ),
            Block::Toc { depth, .. } => self.toc(*depth, span),
            Block::Bibliography { .. } => self.bibliography(span),
            Block::Cell(cell) => self.cell(cell),
        }
    }

    fn definitions(
        &mut self, items: &'d [DefinitionItem], span: Option<&SourceSpan>,
    ) -> String {
        let mut out =
            self.tag("dl", &Attrs::default(), &[], &[], &[], span, false);
        out.push('\n');
        for item in items {
            out.push_str(&format!("<dt>{}</dt>\n", self.inlines(&item.term)));
            for definition in &item.definitions {
                out.push_str(&format!(
                    "<dd>\n{}</dd>\n",
                    self.blocks(definition)
                ));
            }
        }
        out.push_str("</dl>\n");
        out
    }

    fn display_math(
        &mut self, source: &str, dialect: MathDialect, attrs: &Attrs,
        number: Option<&str>, span: Option<&SourceSpan>,
    ) -> String {
        let classes = if number.is_some() {
            vec!["equation", "numbered"]
        } else {
            vec!["equation"]
        };
        let open = self.tag("div", attrs, &classes, &[], &[], span, false);
        let equation = self.math(
            source,
            dialect,
            true,
            if self.abstract_mode { None } else { span },
        );
        let number = number.map_or(String::new(), |n| {
            format!("<span class=\"equation-number\">({})</span>", escape(n))
        });
        format!("{open}{equation}{number}</div>\n")
    }

    fn callout(
        &mut self, kind: &str, title: Option<&'d [Inline]>,
        blocks: &'d [Block], attrs: &Attrs, span: Option<&SourceSpan>,
    ) -> String {
        let class = format!("callout-{kind}");
        let open = self.tag(
            "aside",
            attrs,
            &["callout", &class],
            &[value("role", "note")],
            &["kind", "title"],
            span,
            false,
        );
        let title = match title {
            Some(title) => self.inlines(title),
            None => self.callout_title(kind),
        };
        format!(
            "{open}\n<p class=\"callout-title\">{title}</p>\n{}</aside>\n",
            self.blocks(blocks)
        )
    }

    fn div(
        &mut self, attrs: &Attrs, blocks: &'d [Block],
        span: Option<&SourceSpan>,
    ) -> String {
        let mut own = Vec::new();
        let mut consumed = Vec::new();
        if attrs.classes.iter().any(|class| class == "columns") {
            consumed.push("widths");
            if let Some(widths) = attrs.pairs.get("widths") {
                own.push(value(
                    "style",
                    format!("grid-template-columns:{widths}"),
                ));
            }
        }
        if attrs.classes.iter().any(|class| class == "column") {
            consumed.push("width");
        }
        format!(
            "{}\n{}</div>\n",
            self.tag("div", attrs, &[], &own, &consumed, span, false),
            self.blocks(blocks)
        )
    }

    fn callout_title(&self, kind: &str) -> String {
        let known = match kind {
            "note" => Some(Term::Note),
            "tip" => Some(Term::Tip),
            "important" => Some(Term::Important),
            "warning" => Some(Term::Warning),
            "caution" => Some(Term::Caution),
            _ => None,
        };
        let title = known.map_or_else(
            || {
                let mut chars = kind.chars();
                chars.next().map_or(String::new(), |first| {
                    first.to_uppercase().chain(chars).collect()
                })
            },
            |title| term(&self.lang, title),
        );
        escape(&title)
    }
}

fn value(name: &str, text: impl Into<String>) -> (&str, Option<String>) {
    (name, Some(text.into()))
}

fn start_tag(
    name: &str, attrs: &Attrs, classes: &[&str],
    own: &[(&str, Option<String>)], consumed: &[&str],
    positions: &[(&str, Option<String>)], keep_id: bool,
) -> String {
    let mut attributes: Vec<(String, Option<String>)> = Vec::new();
    if let Some(id) = attrs.id.as_ref().filter(|_| keep_id) {
        attributes.push(("id".into(), Some(id.clone())));
    }
    let classes: Vec<_> = classes
        .iter()
        .copied()
        .chain(attrs.classes.iter().map(String::as_str))
        .collect();
    if !classes.is_empty() {
        attributes.push(("class".into(), Some(classes.join(" "))));
    }
    attributes.extend(
        own.iter().map(|(name, value)| (name.to_string(), value.clone())),
    );
    let mut reserved: BTreeSet<_> =
        attributes.iter().map(|(name, _)| name.clone()).collect();
    reserved.extend(positions.iter().map(|(name, _)| name.to_string()));
    for (key, text) in &attrs.pairs {
        if consumed.contains(&key.as_str())
            || matches!(key.as_str(), "custom-style" | "ansi")
        {
            continue;
        }
        let name = if matches!(
            key.as_str(),
            "style" | "title" | "lang" | "dir" | "role"
        ) || key.starts_with("data-")
            || key.starts_with("aria-")
        {
            key.clone()
        } else {
            format!("data-{key}")
        };
        if name == "style"
            && let Some((_, Some(style))) =
                attributes.iter_mut().find(|(name, _)| name == "style")
        {
            style.push(';');
            style.push_str(text);
        } else if reserved.insert(name.clone()) {
            attributes.push((name, Some(text.clone())));
        }
    }
    for (name, text) in positions {
        if !attributes.iter().any(|(written, _)| written == name) {
            attributes.push((name.to_string(), text.clone()));
        }
    }
    let mut out = format!("<{name}");
    for (name, text) in attributes {
        out.push(' ');
        out.push_str(&name);
        if let Some(text) = text {
            out.push_str(&format!("=\"{}\"", escape(&text)));
        }
    }
    out.push('>');
    out
}

fn number_html(number: Option<&str>) -> String {
    number.map_or(String::new(), |number| {
        format!("<span class=\"number\">{}</span> ", escape(number))
    })
}

fn footnote_reference(number: u32, ordinal: u32) -> String {
    let id = if ordinal <= 1 {
        format!("fnref-{number}")
    } else {
        format!("fnref-{number}-{ordinal}")
    };
    format!(
        "<sup class=\"footnote-ref\"><a id=\"{id}\" href=\"#fn-{number}\" role=\"doc-noteref\">{number}</a></sup>"
    )
}

impl<'d> Emitter<'d, '_, '_> {
    fn list(
        &mut self, kind: &ListKind, tight: bool, items: &'d [ListItem],
        span: Option<&SourceSpan>,
    ) -> String {
        let (tag, own) = match kind {
            ListKind::Bullet => ("ul", Vec::new()),
            ListKind::Ordered { start } => (
                "ol",
                if *start == 1 {
                    Vec::new()
                } else {
                    vec![value("start", start.to_string())]
                },
            ),
        };
        let task = items.iter().any(|item| item.checked.is_some());
        let classes = if task { vec!["task-list"] } else { Vec::new() };
        let mut out =
            self.tag(tag, &Attrs::default(), &classes, &own, &[], span, false);
        out.push('\n');
        for item in items {
            out.push_str(&self.list_item(item, tight));
        }
        out.push_str(&format!("</{tag}>\n"));
        out
    }

    fn list_item(&mut self, item: &'d ListItem, tight: bool) -> String {
        let open = if item.checked.is_some() {
            "<li class=\"task-list-item\">"
        } else {
            "<li>"
        };
        let checkbox = item.checked.map_or(String::new(), |checked| {
            format!(
                "<input type=\"checkbox\" disabled{}>",
                if checked { " checked" } else { "" }
            )
        });
        if item.blocks.is_empty() {
            return format!("{open}{checkbox}</li>\n");
        }
        if tight
            && let [Block::Paragraph { inlines, span }] = item.blocks.as_slice()
        {
            let previous = self.current_span;
            if !self.abstract_mode {
                self.current_span = span.as_ref().or(previous);
            }
            let content = self.inlines(inlines);
            self.current_span = previous;
            return format!(
                "{open}{checkbox}{}{}</li>\n",
                if checkbox.is_empty() { "" } else { " " },
                content
            );
        }
        let mut out = open.to_string();
        if !matches!(item.blocks.first(), Some(Block::Paragraph { .. })) {
            out.push_str(&checkbox);
        }
        out.push('\n');
        for (index, block) in item.blocks.iter().enumerate() {
            if let Block::Paragraph { inlines, span } = block {
                let previous = self.current_span;
                if !self.abstract_mode {
                    self.current_span = span.as_ref().or(previous);
                }
                let prefix = if index == 0 && !checkbox.is_empty() {
                    format!("{checkbox} ")
                } else {
                    String::new()
                };
                let content = format!("{prefix}{}", self.inlines(inlines));
                if tight {
                    out.push_str(&format!("{content}\n"));
                } else {
                    out.push_str(&format!(
                        "{}{content}</p>\n",
                        self.tag(
                            "p",
                            &Attrs::default(),
                            &[],
                            &[],
                            &[],
                            span.as_ref(),
                            false
                        )
                    ));
                }
                self.current_span = previous;
            } else {
                out.push_str(&self.block(block));
            }
        }
        out.push_str("</li>\n");
        out
    }

    fn code_block(
        &mut self, lang: Option<&str>, text: &str, attrs: &Attrs,
        span: Option<&SourceSpan>,
    ) -> String {
        let code = CodeAttrs::from_attrs(attrs);
        let output = attrs.classes.iter().any(|class| {
            matches!(
                class.as_str(),
                "output-text" | "output-error" | "output-json"
            ) || class.starts_with("output-stream-")
        });
        let syntax = if output {
            SyntaxChoice::Plain
        } else {
            resolve_syntax(lang, code.plain)
        };
        if matches!(syntax, SyntaxChoice::Unknown) {
            let mut diagnostic = Diagnostic::info(
                "code-language-unknown",
                format!(
                    "unknown code language `{}`; used plain text",
                    lang.unwrap_or_default()
                ),
            );
            diagnostic.span = span.cloned();
            diagnostic.path = Some(
                span.and_then(|span| span.file.clone())
                    .unwrap_or_else(|| self.document.source.path.clone()),
            );
            self.opts.diagnostics.push(diagnostic);
        }
        let mut attrs = attrs.clone();
        attrs
            .classes
            .retain(|class| !matches!(class.as_str(), "numbered" | "plain"));
        let mut classes = vec!["hl-code"];
        if code.numbered {
            classes.push("numbered");
        }
        let own = if code.numbered && code.start != 1 {
            vec![value(
                "style",
                format!("counter-reset:line {}", code.start - 1),
            )]
        } else {
            Vec::new()
        };
        let consumed = [
            "start", "highlight", "lines", "caption", "include", "trim",
            "escape", "ansi",
        ];
        let open =
            self.tag("pre", &attrs, &classes, &own, &consumed, span, false);
        let language = lang.map_or(String::new(), |lang| {
            format!(" class=\"language-{}\"", escape(lang))
        });
        let lines = if let Some(pair) = attrs.pairs.get("ansi") {
            crate::notebook::ansi::to_html(&crate::notebook::ansi::parse(pair))
                .into_iter()
                .enumerate()
                .map(|(index, line)| {
                    let class = if code
                        .is_highlighted(code.start.saturating_add(index as u64))
                    {
                        "line highlight"
                    } else {
                        "line"
                    };
                    format!("<span class=\"{class}\">{line}</span>")
                })
                .collect::<Vec<_>>()
                .join("\n")
        } else {
            code_lines(&syntax, text, &code)
        };
        format!("{open}<code{language}>{}</code></pre>\n", lines)
    }

    fn figure(
        &mut self, kind: FigureKind, caption: Option<&'d [Inline]>,
        body: &'d [Block], attrs: &Attrs, number: Option<&str>,
        span: Option<&SourceSpan>,
    ) -> String {
        let class = match kind {
            FigureKind::Image => "kind-image",
            FigureKind::Table => "kind-table",
            FigureKind::Listing => "kind-listing",
            FigureKind::Other => "kind-other",
        };
        let open = self.tag(
            "figure",
            attrs,
            &["figure", class],
            &[],
            &["caption", "kind"],
            span,
            false,
        );
        let first = matches!(kind, FigureKind::Table | FigureKind::Listing);
        let before = if first {
            self.figure_caption(kind, caption, attrs, number)
        } else {
            String::new()
        };
        let body = if kind == FigureKind::Image
            && let [Block::Paragraph { inlines, .. }] = body
        {
            format!("{}\n", self.inlines(inlines))
        } else {
            self.blocks(body)
        };
        let after = if first {
            String::new()
        } else {
            self.figure_caption(kind, caption, attrs, number)
        };
        format!("{open}\n{before}{body}{after}</figure>\n")
    }

    fn figure_caption(
        &mut self, kind: FigureKind, caption: Option<&'d [Inline]>,
        attrs: &Attrs, number: Option<&str>,
    ) -> String {
        if number.is_none() && caption.is_none() {
            return String::new();
        }
        let mut out = String::from("<figcaption>");
        if let Some(number) = number {
            let kind = match kind {
                FigureKind::Table => LabelKind::Table,
                FigureKind::Listing => LabelKind::Listing,
                FigureKind::Image | FigureKind::Other => LabelKind::Figure,
            };
            let supplement = attrs
                .id
                .as_ref()
                .and_then(|id| self.document.resolved.labels.get(id))
                .map_or_else(
                    || supplement(kind, &self.lang),
                    |info| info.supplement.clone(),
                );
            let separator = if caption.is_some() {
                caption_separator(&self.lang)
            } else {
                ""
            };
            let label = separator.trim_end_matches(' ');
            let tail = &separator[label.len()..];
            out.push_str(&format!(
                "<span class=\"caption-label\">{}{}</span>{tail}",
                escape(&format!("{supplement}\u{a0}{number}")),
                escape(label)
            ));
        }
        if let Some(caption) = caption {
            out.push_str(&self.inlines(caption));
        }
        out.push_str("</figcaption>\n");
        out
    }

    fn table(
        &mut self, columns: &[ColumnSpec], head: &'d [Row], body: &'d [Row],
        foot: &'d [Row], attrs: &Attrs, span: Option<&SourceSpan>,
    ) -> String {
        let mut out = self.tag("table", attrs, &[], &[], &[], span, false);
        out.push('\n');
        if columns.iter().any(|column| column.width.is_some()) {
            out.push_str("<colgroup>\n");
            for column in columns {
                match column.width {
                    Some(width) => {
                        let width = format!("{:.2}", f64::from(width) * 100.0);
                        let width =
                            width.trim_end_matches('0').trim_end_matches('.');
                        out.push_str(&format!(
                            "<col style=\"width:{width}%\">\n"
                        ));
                    }
                    None => out.push_str("<col>\n"),
                }
            }
            out.push_str("</colgroup>\n");
        }
        for (tag, rows) in [("thead", head), ("tbody", body), ("tfoot", foot)] {
            if rows.is_empty() {
                continue;
            }
            out.push_str(&format!("<{tag}>\n"));
            out.push_str(&self.table_rows(rows, columns, tag == "thead"));
            out.push_str(&format!("</{tag}>\n"));
        }
        out.push_str("</table>\n");
        out
    }

    fn table_rows(
        &mut self, rows: &'d [Row], columns: &[ColumnSpec], head: bool,
    ) -> String {
        let mut remaining = vec![0u32; columns.len()];
        let mut out = String::new();
        for row in rows {
            out.push_str("<tr>\n");
            let mut column = 0;
            for cell in &row.cells {
                while remaining.get(column).is_some_and(|&span| span > 0) {
                    column += 1;
                }
                let align = cell.align.unwrap_or_else(|| {
                    columns
                        .get(column)
                        .map_or(Align::Default, |column| column.align)
                });
                let class = match align {
                    Align::Default => "",
                    Align::Left => " class=\"align-left\"",
                    Align::Center => " class=\"align-center\"",
                    Align::Right => " class=\"align-right\"",
                };
                let tag = if cell.header { "th" } else { "td" };
                out.push_str(&format!("<{tag}{class}"));
                if cell.header {
                    out.push_str(if head {
                        " scope=\"col\""
                    } else {
                        " scope=\"row\""
                    });
                }
                if cell.colspan > 1 {
                    out.push_str(&format!(" colspan=\"{}\"", cell.colspan));
                }
                if cell.rowspan > 1 {
                    out.push_str(&format!(" rowspan=\"{}\"", cell.rowspan));
                }
                out.push('>');
                out.push_str(&self.inlines(&cell.inlines));
                out.push_str(&format!("</{tag}>\n"));
                let end = column
                    .saturating_add(cell.colspan as usize)
                    .min(remaining.len());
                for slot in &mut remaining[column.min(end)..end] {
                    *slot = cell.rowspan;
                }
                column = end;
            }
            for slot in &mut remaining {
                *slot = slot.saturating_sub(1);
            }
            out.push_str("</tr>\n");
        }
        out
    }

    fn cell(&mut self, cell: &'d Cell) -> String {
        let mut content = String::new();
        if cell.show_input {
            content.push_str(&self.cell_input(cell));
        }
        let outputs = if cell.show_output {
            self.cell_outputs(cell)
        } else {
            String::new()
        };
        if !outputs.is_empty() {
            content.push_str(&format!(
                "<div class=\"cell-outputs\">\n{outputs}</div>\n"
            ));
        }
        if content.is_empty() {
            return content;
        }
        let mut attrs = cell.attrs.clone();
        attrs
            .classes
            .retain(|class| !matches!(class.as_str(), "numbered" | "plain"));
        let open = self.tag(
            "div",
            &attrs,
            &["cell"],
            &[value("data-cell", cell.index.to_string())],
            &["start", "highlight", "lines"],
            cell.span.as_ref(),
            false,
        );
        format!("{open}\n{content}</div>\n")
    }

    fn cell_input(&mut self, cell: &Cell) -> String {
        let mut content = String::new();
        let mut attrs = Attrs::default();
        attrs.classes = cell
            .attrs
            .classes
            .iter()
            .filter(|class| matches!(class.as_str(), "numbered" | "plain"))
            .cloned()
            .collect();
        attrs.pairs = cell
            .attrs
            .pairs
            .iter()
            .filter(|(key, _)| {
                matches!(key.as_str(), "start" | "highlight" | "lines")
            })
            .map(|(key, value)| (key.clone(), value.clone()))
            .collect();
        content.push_str("<div class=\"cell-input\">\n");
        if self.opts.config.notebook.show_prompts {
            let number = cell
                .execution_count
                .map_or(" ".into(), |number| number.to_string());
            content.push_str(&format!(
                "<div class=\"cell-prompt\">In [{number}]:</div>\n"
            ));
        }
        let lang =
            (!cell.language.is_empty()).then_some(cell.language.as_str());
        content.push_str(&self.code_block(lang, &cell.source, &attrs, None));
        content.push_str("</div>\n");
        content
    }

    fn cell_outputs(&mut self, cell: &'d Cell) -> String {
        let mut outputs = String::new();
        for output in &cell.outputs {
            let picked = output.pick("html");
            if picked.is_empty() {
                continue;
            }
            let body = self.blocks(picked);
            if body.is_empty() {
                continue;
            }
            let mime = output
                .candidates
                .iter()
                .find(|candidate| {
                    std::ptr::eq(candidate.blocks.as_slice(), picked)
                })
                .map_or("", |candidate| candidate.mime.as_str());
            let classes = match &output.kind {
                OutputKind::Stream { name } => {
                    format!("output output-stream {}", escape(name))
                }
                OutputKind::Error { .. } => "output output-error".into(),
                OutputKind::Display => "output output-display".into(),
                OutputKind::Result => "output output-result".into(),
            };
            outputs.push_str(&format!(
                "<div class=\"{classes}\" data-mime=\"{}\">\n",
                escape(mime)
            ));
            if matches!(output.kind, OutputKind::Result)
                && self.opts.config.notebook.show_prompts
                && let Some(number) = output.execution_count
            {
                outputs.push_str(&format!(
                    "<div class=\"cell-prompt\">Out [{number}]:</div>\n"
                ));
            }
            outputs.push_str(&body);
            outputs.push_str("</div>\n");
        }
        outputs
    }

    fn title_block(&mut self) -> String {
        let meta = &self.document.meta;
        if meta.title.is_none()
            && meta.subtitle.is_none()
            && meta.authors.is_empty()
            && meta.date.is_none()
            && meta.abstract_.is_none()
        {
            return String::new();
        }
        let mut out = String::from("<header class=\"title-block\">\n");
        for (tag, class, text) in
            [("h1", "title", &meta.title), ("p", "subtitle", &meta.subtitle)]
        {
            if let Some(text) = text {
                out.push_str(&format!(
                    "<{tag} class=\"{class}\">{}</{tag}>\n",
                    escape(text)
                ));
            }
        }
        if !meta.authors.is_empty() {
            out.push_str("<div class=\"authors\">\n");
            for author in &meta.authors {
                out.push_str(&format!(
                    "<p class=\"author\"><span class=\"author-name\">{}</span>",
                    escape(&author.name)
                ));
                if let Some(affiliation) = &author.affiliation {
                    out.push_str(&format!(
                        " <span class=\"author-affiliation\">{}</span>",
                        escape(affiliation)
                    ));
                }
                if let Some(email) = &author.email {
                    out.push_str(&format!(
                        " <a class=\"author-email\" href=\"mailto:{}\">{}</a>",
                        escape(email),
                        escape(email)
                    ));
                }
                if let Some(id) = &author.id {
                    out.push_str(&format!(
                        " <span class=\"author-id\">{}</span>",
                        escape(id)
                    ));
                }
                out.push_str("</p>\n");
            }
            out.push_str("</div>\n");
        }
        if let Some(date) = &meta.date {
            out.push_str(&format!("<p class=\"date\">{}</p>\n", escape(date)));
        }
        if let Some(abstract_) = &meta.abstract_ {
            out.push_str(&format!("<section class=\"abstract\" role=\"doc-abstract\">\n<p class=\"abstract-title\">{}</p>\n", self.variable_title("abstract-title", Term::Abstract)));
            self.abstract_mode = true;
            out.push_str(&self.blocks(abstract_));
            self.abstract_mode = false;
            out.push_str("</section>\n");
        }
        out.push_str("</header>\n");
        out
    }

    fn variable_title(&self, key: &str, default: Term) -> String {
        escape(
            self.document
                .meta
                .vars
                .get(key)
                .and_then(serde_json::Value::as_str)
                .map_or_else(|| term(&self.lang, default), str::to_string)
                .as_str(),
        )
    }

    fn toc(&mut self, depth: u8, span: Option<&SourceSpan>) -> String {
        let entries: Vec<_> = self
            .document
            .resolved
            .toc
            .iter()
            .filter(|entry| entry.level <= depth)
            .collect();
        if entries.is_empty() {
            return String::new();
        }
        let open = self.tag(
            "nav",
            &Attrs::default(),
            &["toc"],
            &[value("role", "doc-toc")],
            &[],
            span,
            false,
        );
        let previous = self.inline_ids;
        self.inline_ids = false;
        let entries = self.toc_list(&entries, &mut 0, 0);
        self.inline_ids = previous;
        format!(
            "{open}\n<p class=\"toc-title\">{}</p>\n{entries}</nav>\n",
            self.variable_title("toc-title", Term::Contents)
        )
    }

    fn toc_list(
        &mut self, entries: &[&'d TocEntry], at: &mut usize, parent: u8,
    ) -> String {
        let mut out = String::from("<ol>\n");
        while *at < entries.len() && entries[*at].level > parent {
            let entry = entries[*at];
            *at += 1;
            let link = if entry.anchor == "refs"
                && let Some(title) = self
                    .document
                    .meta
                    .vars
                    .get("reference-section-title")
                    .and_then(serde_json::Value::as_str)
            {
                format!("<a href=\"#refs\">{}</a>", escape(title))
            } else {
                let open = format!(
                    "<a href=\"#{}\">{}",
                    escape(&entry.anchor),
                    number_html(entry.number.as_deref())
                );
                self.anchor(open, &entry.inlines)
            };
            out.push_str(&format!("<li>{link}"));
            if entries.get(*at).is_some_and(|next| next.level > entry.level) {
                out.push('\n');
                out.push_str(&self.toc_list(entries, at, entry.level));
            }
            out.push_str("</li>\n");
        }
        out.push_str("</ol>\n");
        out
    }

    fn bibliography(&mut self, span: Option<&SourceSpan>) -> String {
        let Some(bibliography) = &self.document.resolved.bibliography else {
            return String::new();
        };
        let classes = if bibliography.hanging_indent {
            vec!["references", "csl-bib-body", "hanging-indent"]
        } else {
            vec!["references", "csl-bib-body"]
        };
        let open = self.tag(
            "section",
            &Attrs::with_id("refs"),
            &classes,
            &[value("role", "doc-bibliography")],
            &[],
            span,
            false,
        );
        let mut out = format!(
            "{open}\n<h1 class=\"references-title\">{}</h1>\n",
            self.variable_title("reference-section-title", Term::Bibliography)
        );
        for entry in &bibliography.entries {
            out.push_str(&format!(
                "<div id=\"ref-{}\" class=\"csl-entry\">",
                escape(&entry.key)
            ));
            if let Some(prefix) = &entry.prefix {
                out.push_str(&format!("<div class=\"csl-left-margin\">{}</div><div class=\"csl-right-inline\">{}</div>", self.inlines(prefix), self.inlines(&entry.inlines)));
            } else {
                out.push_str(&self.inlines(&entry.inlines));
            }
            out.push_str("</div>\n");
        }
        out.push_str("</section>\n");
        out
    }

    fn footnotes(&mut self) -> String {
        if self.notes.bodies.is_empty() {
            return String::new();
        }
        let mut out = String::from(
            "<section class=\"footnotes\" role=\"doc-endnotes\">\n<hr>\n<ol>\n",
        );
        let bodies: Vec<_> = self
            .notes
            .bodies
            .iter()
            .map(|(&number, &body)| (number, body))
            .collect();
        for (number, body) in bodies {
            self.abstract_mode = body.abstract_mode;
            self.current_span = body.span;
            let count = self.notes.counts.get(&number).copied().unwrap_or(1);
            let backs: Vec<_> = (1..=count).map(|ordinal| {
                let id = if ordinal == 1 { format!("fnref-{number}") } else { format!("fnref-{number}-{ordinal}") };
                let suffix = if ordinal == 1 { String::new() } else { format!("<sup>{ordinal}</sup>") };
                format!("<a class=\"footnote-back\" href=\"#{id}\" role=\"doc-backlink\">↩︎{suffix}</a>")
            }).collect();
            let backs = backs.join(" ");
            out.push_str(&format!("<li id=\"fn-{number}\">\n"));
            if let Some((Block::Paragraph { inlines, span }, before)) =
                body.blocks.split_last()
            {
                out.push_str(&self.blocks(before));
                self.current_span = if body.abstract_mode {
                    None
                } else {
                    span.as_ref().or(body.span)
                };
                let content = self.inlines(inlines);
                let separator = if content.is_empty() { "" } else { " " };
                out.push_str(&format!(
                    "{}{content}{separator}{backs}</p>\n",
                    self.tag(
                        "p",
                        &Attrs::default(),
                        &[],
                        &[],
                        &[],
                        span.as_ref(),
                        false
                    )
                ));
            } else {
                out.push_str(&self.blocks(body.blocks));
                out.push_str(&format!("<p>{backs}</p>\n"));
            }
            out.push_str("</li>\n");
        }
        self.abstract_mode = false;
        self.current_span = None;
        out.push_str("</ol>\n</section>\n");
        out
    }
}
