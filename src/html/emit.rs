/// An equation requested by the HTML emitter.
pub struct MathRequest<'a> {
    /// Original equation source.
    pub source: &'a str,
    /// Source syntax.
    pub dialect: MathDialect,
    /// Whether this equation is a display block.
    pub display: bool,
    /// Its block's source location, if available.
    pub span: Option<&'a SourceSpan>,
}

/// Math representations actually emitted, used when assembling page assets.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize)]
pub struct MathUsage {
    /// LaTeX for client-side KaTeX.
    pub katex: bool,
    /// MathML converted from LaTeX.
    pub mathml: bool,
    /// MathML exported by the Typst compiler.
    pub typst_mathml: bool,
    /// An equation rendered as an image.
    pub image: bool,
}

/// Supplies one inline or display equation element, without id or positions.
pub trait MathHook {
    /// Emits an equation, registering any generated images and diagnostics.
    fn equation(
        &mut self, eq: &MathRequest<'_>, assets: &mut AssetRegistry,
        diagnostics: &mut Diagnostics,
    ) -> String;
    /// The representations emitted so far.
    fn usage(&self) -> MathUsage;
}

/// LaTeX passthrough for KaTeX, with a source fallback for Typst equations.
#[derive(Debug, Default)]
pub struct KatexOnly {
    /// Representations emitted by this hook.
    pub usage: MathUsage,
}

impl MathHook for KatexOnly {
    fn equation(
        &mut self, eq: &MathRequest<'_>, _assets: &mut AssetRegistry,
        diagnostics: &mut Diagnostics,
    ) -> String {
        let class = if eq.display { "display" } else { "inline" };
        let source = escape(eq.source);
        if eq.dialect == MathDialect::Latex {
            self.usage.katex = true;
            return format!(
                "<span class=\"math {class}\" data-math-style=\"{class}\" data-tex=\"{source}\">{source}</span>"
            );
        }
        let mut diagnostic = Diagnostic::warning(
            "math-conversion-failed",
            "html: cannot convert equation (the KaTeX hook accepts LaTeX only); used source",
        );
        diagnostic.span = eq.span.cloned();
        diagnostic.path = eq.span.and_then(|span| span.file.clone());
        diagnostics.push(diagnostic);
        format!(
            "<span class=\"math {class} math-source\" data-tex=\"{source}\"><code>{source}</code></span>"
        )
    }

    fn usage(&self) -> MathUsage {
        self.usage
    }
}

/// Resources and output settings for HTML emission.
pub struct EmitOptions<'a> {
    /// Effective per-document configuration.
    pub config: &'a Config,
    /// Include source-position attributes on blocks.
    pub positions: bool,
    /// Included paths, in the same order as `Document.includes`.
    pub includes: &'a [PathBuf],
    /// Equation renderer for this output.
    pub math: &'a mut dyn MathHook,
    /// Registry for equation images generated by the hook.
    pub assets: &'a mut AssetRegistry,
    /// Findings generated by highlighting or math rendering.
    pub diagnostics: &'a mut Diagnostics,
}

